CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employee_id BIGINT NOT NULL,
    role_code VARCHAR(32) DEFAULT 'employee' NOT NULL,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_password_hash_not_blank CHECK (length(trim(password_hash)) > 0),
    CONSTRAINT ck_users_username_not_blank CHECK (length(trim(username)) > 0),
    CONSTRAINT fk_users_employee_id_employees FOREIGN KEY(employee_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_users_role_code_roles FOREIGN KEY(role_code) REFERENCES roles (code) ON DELETE RESTRICT,
    CONSTRAINT uq_users_employee_id UNIQUE (employee_id)
);

