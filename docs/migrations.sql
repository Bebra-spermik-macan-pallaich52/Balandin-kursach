CREATE TABLE employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_id BIGINT NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    position VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    is_active BOOLEAN DEFAULT true NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_employees PRIMARY KEY (id),
    CONSTRAINT ck_employees_email_format CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    CONSTRAINT ck_employees_first_name_not_blank CHECK (length(trim(first_name)) > 0),
    CONSTRAINT ck_employees_last_name_not_blank CHECK (length(trim(last_name)) > 0),
    CONSTRAINT ck_employees_phone_not_blank CHECK (length(trim(phone)) > 0),
    CONSTRAINT ck_employees_position_not_blank CHECK (length(trim(position)) > 0),
    CONSTRAINT fk_employees_department_id_departments FOREIGN KEY(department_id) REFERENCES departments (id) ON DELETE RESTRICT
