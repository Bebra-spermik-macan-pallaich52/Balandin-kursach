CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_id BIGINT NOT NULL,
    title VARCHAR(250) NOT NULL,
    description TEXT,
    assignee_id BIGINT,
    created_by_id BIGINT NOT NULL,
    status_code VARCHAR(32) DEFAULT 'new' NOT NULL,
    priority SMALLINT DEFAULT '2' NOT NULL,
    due_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    completed_by_id BIGINT,
    is_archived BOOLEAN DEFAULT false NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    CONSTRAINT pk_tasks PRIMARY KEY (id),
    CONSTRAINT ck_tasks_completion_consistent CHECK ((status_code = 'done' AND completed_at IS NOT NULL AND completed_by_id IS NOT NULL AND assignee_id IS NOT NULL) OR (status_code <> 'done' AND completed_at IS NULL AND completed_by_id IS NULL)),
    CONSTRAINT ck_tasks_completion_after_creation CHECK (completed_at IS NULL OR completed_at >= created_at),
    CONSTRAINT ck_tasks_due_after_creation CHECK (due_at IS NULL OR due_at >= created_at),
    CONSTRAINT ck_tasks_title_not_blank CHECK (length(trim(title)) > 0),
    CONSTRAINT ck_tasks_priority_range CHECK (priority BETWEEN 1 AND 4),
    CONSTRAINT fk_tasks_assignee_id_employees FOREIGN KEY(assignee_id) REFERENCES employees (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tasks_completed_by_id_users FOREIGN KEY(completed_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tasks_created_by_id_users FOREIGN KEY(created_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tasks_department_id_departments FOREIGN KEY(department_id) REFERENCES departments (id) ON DELETE RESTRICT,
    CONSTRAINT fk_tasks_status_code_task_statuses FOREIGN KEY(status_code) REFERENCES task_statuses (code) ON DELETE RESTRICT
);

