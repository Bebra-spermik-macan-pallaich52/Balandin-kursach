CREATE TABLE task_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    task_id BIGINT NOT NULL,
    from_status_code VARCHAR(32),
    to_status_code VARCHAR(32) NOT NULL,
    changed_by_id BIGINT NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    comment TEXT,
    CONSTRAINT pk_task_status_history PRIMARY KEY (id),
    CONSTRAINT ck_task_status_history_status_changed CHECK (from_status_code IS NULL OR from_status_code <> to_status_code),
    CONSTRAINT fk_task_status_history_changed_by_id_users FOREIGN KEY(changed_by_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_status_history_from_status_code_task_statuses FOREIGN KEY(from_status_code) REFERENCES task_statuses (code) ON DELETE RESTRICT,
    CONSTRAINT fk_task_status_history_task_id_tasks FOREIGN KEY(task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_status_history_to_status_code_task_statuses FOREIGN KEY(to_status_code) REFERENCES task_statuses (code) ON DELETE RESTRICT
);

COMMENT ON TABLE task_status_history IS 'События смены состояния. Заполняются сервисом в транзакции изменения задачи';

COMMENT ON COLUMN task_status_history.id IS 'Идентификатор события';

COMMENT ON COLUMN task_status_history.task_id IS 'Задача, состояние которой изменилось';

COMMENT ON COLUMN task_status_history.from_status_code IS 'Предыдущее состояние; NULL при создании';

COMMENT ON COLUMN task_status_history.to_status_code IS 'Новое состояние';

COMMENT ON COLUMN task_status_history.changed_by_id IS 'Пользователь, выполнивший действие';

COMMENT ON COLUMN task_status_history.changed_at IS 'Время события';

COMMENT ON COLUMN task_status_history.comment IS 'Комментарий к изменению';

CREATE INDEX ix_task_status_history_changed_by_id ON task_status_history (changed_by_id);

CREATE INDEX ix_task_status_history_task_changed ON task_status_history (task_id, changed_at);

